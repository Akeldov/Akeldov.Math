namespace Akeldov.Math.Spatial2D.Contours
{
    /// <summary>
    /// Specifies the traversal direction along a closed contour.
    /// </summary>
    public enum ContourDirection
    {
        /// <summary>
        /// Traverses the contour in the counterclockwise direction.
        /// </summary>
        Counterclockwise = 0,

        /// <summary>
        /// Traverses the contour in the clockwise direction.
        /// </summary>
        Clockwise = 1
    }
}
