        private static void AddAlphabetGlyphs(Dictionary<char, byte[]> glyphs)
        {
            foreach (string entry in AlphabetData.Split('\n'))
            {
                var rows = new byte[GlyphHeight];
                for (int y = 0; y < GlyphHeight; y++)
                    rows[y] = Convert.ToByte(entry.Substring(2 + y * 2, 2), 16);
                glyphs.Add(entry[0], rows);
            }
        }
